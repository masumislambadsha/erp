// Regenerates db/migrations/0004_pgboss.superuser.sql from the pinned pg-boss version.
// Run it from apps/api, where pg-boss is installed:
//   (cd apps/api && node ../../scripts/gen-pgboss-migration.mjs > ../../db/migrations/0004_pgboss.superuser.sql)
// The output is committed and never edited by hand. A newer pg-boss gets a NEW migration file
// (getMigrationPlans), never a changed 0004.
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// Resolved from the working directory (apps/api), where pg-boss is installed.
const { getConstructionPlans } = await import(
  pathToFileURL(resolve('node_modules/pg-boss/dist/index.js')).href
);

const QUEUES = ['document.submitted', 'integrity.nightly', 'maintenance.jobs'];
// The runner supplies the transaction, and erp_owner may not take advisory locks: drop pg-boss's own
// BEGIN, lock settings, advisory lock, CREATE SCHEMA (done above) and COMMIT.
const DROP = [
  /^BEGIN;$/,
  /^SET LOCAL lock_timeout/,
  /^SET LOCAL idle_in_transaction_session_timeout/,
  /^SELECT pg_advisory_xact_lock/,
  /^CREATE SCHEMA IF NOT EXISTS pgboss;$/,
  /^COMMIT;$/,
];
const sql = getConstructionPlans('pgboss')
  .split('\n')
  .filter((line) => !DROP.some((re) => re.test(line.trim())))
  .join('\n');

process.stdout
  .write(`-- Milestone 4: the pg-boss job queue (v12.38.1), installed by migration so the app role needs no DDL.
-- Superuser-only because CREATE SCHEMA needs CREATE on the database; everything else is created by
-- erp_owner, so erp_app owns nothing (kernel test K02). Generated by scripts/gen-pgboss-migration.mjs.
-- pg-boss runs with migrate, supervise and schedule switched off and queue statistics not persisted:
-- those need DDL or advisory locks, and erp_app has neither (K08). Queues are created here, once.

CREATE SCHEMA pgboss AUTHORIZATION erp_owner;
SET ROLE erp_owner;

${sql}

${QUEUES.map((q) => `SELECT pgboss.create_queue('${q}', '{"policy": "standard", "retryLimit": 3, "retryDelay": 30, "retryBackoff": true, "expireInSeconds": 900}'::jsonb);`).join('\n')}

GRANT USAGE ON SCHEMA pgboss TO erp_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA pgboss TO erp_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA pgboss TO erp_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA pgboss TO erp_app;
RESET ROLE;
`);
